/// The result of converting result columns: the SQL columns, the sorting, the grouping, and a
/// `column_annotations` vector that is positionally aligned with `columns` (one entry per emitted
/// column, `None` where the column has no annotation).
pub struct ConvertedResultColumns {
    pub columns: Vec<Column>,
    pub sorting: Vec<SortEntry>,
    pub grouping: Vec<SqlExpr>,
    pub column_annotations: Vec<Option<AnnotationValue>>,
    /// The logical output name of each emitted column, positionally aligned with `columns`. Used by
    /// query pipelines to determine the columns of the synthetic table that represents a stage's
    /// output. A column's name is its alias if it has one, the column name if it is a simple column
    /// reference, or an autogenerated `column_N` otherwise.
    pub output_names: Vec<String>,
    /// Whether each emitted column has a name of its own — an alias, or the name of the column it
    /// references — rather than an autogenerated `column_N`. Positionally aligned with `columns`.
    pub named: Vec<bool>,
    /// The inferred type of each emitted column, positionally aligned with `columns`. Used by query
    /// pipelines to type the columns of the synthetic table that represents a stage's output.
    pub output_types: Vec<ValueType>,
}

/// The pieces of [`ConvertedResultColumns`] that are built up one result column at a time.
#[derive(Default)]
struct Output {
    columns: Vec<Column>,
    column_annotations: Vec<Option<AnnotationValue>>,
    output_names: Vec<String>,
    named: Vec<bool>,
    output_types: Vec<ValueType>,
    sorting_stack: SortingStack,
    grouping_stack: GroupingStack,
    /// The first result column that doesn't fit a grouped query (being neither a grouping column
    /// nor an aggregate), if the query emits one: how it fails to fit, and where it was written.
    /// Such a column is only valid when the query has no grouping at all.
    misfit: Option<(GroupFit, Loc)>,
}

/// Determines the logical output name for a (non-glob) result column: its alias if present,
/// otherwise the trailing column name if the expression is a simple column reference, otherwise an
/// autogenerated name based on its position. Also returns whether the name is of the first two
/// kinds (rather than autogenerated).
fn output_name_for_spec(alias: &Option<String>, expr: &Expr, index: usize) -> (String, bool) {
    if let Some(alias) = alias {
        return (alias.clone(), true);
    }
    if let ExprKind::Path(parts) = &expr.kind {
        if let Some(PathPartKind::Column(name)) = parts.last().map(|part| &part.kind) {
            return (name.clone(), true);
        }
    }
    (format!("column_{}", index + 1), false)
}

/// Whether an expression aggregates *related* records: a path to many records (e.g. `#comments`,
/// which counts them, or `#comments.created_at%max`), or a "has quantity" expression (e.g.
/// `++#comments`). Such a value is computed for each record of the table being queried, so in a
/// grouped query it's no more an aggregate than a plain column is.
fn contains_related_aggregate(expr: &Expr) -> bool {
    let has_to_many_part = |parts: &[PathPart]| {
        parts
            .iter()
            .any(|part| matches!(part.kind, PathPartKind::TableWithMany(_)))
    };
    let any = |exprs: &[Expr]| exprs.iter().any(contains_related_aggregate);
    let side = |side: &ComparisonSide| match side {
        ComparisonSide::Expr(e) => contains_related_aggregate(e),
        ComparisonSide::Expansion(cs) => cs.entries.iter().any(contains_related_aggregate),
        ComparisonSide::Range(r) => {
            contains_related_aggregate(&r.lower.expr) || contains_related_aggregate(&r.upper.expr)
        }
    };
    match &expr.kind {
        ExprKind::Path(parts) => has_to_many_part(parts),
        ExprKind::HasQuantity(_) => true,
        ExprKind::Call(call) => any(&call.args),
        ExprKind::Product(a, b)
        | ExprKind::Quotient(a, b)
        | ExprKind::Sum(a, b)
        | ExprKind::Difference(a, b) => {
            contains_related_aggregate(a) || contains_related_aggregate(b)
        }
        ExprKind::Not(e) => contains_related_aggregate(e),
        ExprKind::FormatString(parts) => parts
            .iter()
            .filter_map(|p| p.expr())
            .any(contains_related_aggregate),
        ExprKind::Case(case) => {
            case.variants.iter().any(|v| {
                contains_related_aggregate(&v.condition) || contains_related_aggregate(&v.value)
            }) || contains_related_aggregate(&case.fallback)
        }
        ExprKind::ConditionSet(cs) => any(&cs.entries),
        ExprKind::ScopedConditionSet(s) => {
            has_to_many_part(&s.path) || any(&s.condition_set.entries)
        }
        ExprKind::Comparison(c) => side(&c.left) || side(&c.right),
        ExprKind::AnonymousFunctionCall(c) => {
            any(&c.args)
                || c.body
                    .assignments
                    .iter()
                    .any(|a| contains_related_aggregate(&a.expr))
                || contains_related_aggregate(&c.body.expr)
        }
        ExprKind::FunctionArg(f) => {
            f.body
                .assignments
                .iter()
                .any(|a| contains_related_aggregate(&a.expr))
                || contains_related_aggregate(&f.body.expr)
        }
        ExprKind::Window(_)
        | ExprKind::Subquery(_)
        | ExprKind::Number(_)
        | ExprKind::Date(_)
        | ExprKind::Timestamp(_)
        | ExprKind::Duration(_)
        | ExprKind::String(_)
        | ExprKind::Variable(_) => false,
    }
}

/// How a result column or sorting expression of a grouped query relates to its groups.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum GroupFit {
    /// It contains an aggregate function over the records of each group, so it has a value for
    /// each group.
    Aggregated,
    /// It has a value for each record rather than each group, and that value aggregates related
    /// records (e.g. `#comments`), which deserves an error message of its own.
    RelatedAggregate,
    /// It has a value for each record rather than each group.
    Unaggregated,
}

impl GroupFit {
    /// Classifies `expr`. This must be done before the expression is compiled, since compiling
    /// consumes it.
    ///
    /// Only an aggregate over the grouped records themselves (`created_at%max`, `%count`) makes an
    /// expression fit: a window function doesn't (combining `\g` with one isn't supported), and nor
    /// does an aggregate of *related* records, of which each grouped record has its own.
    fn of(expr: &Expr) -> Self {
        if contains_local_aggregate(expr) {
            GroupFit::Aggregated
        } else if contains_related_aggregate(expr) {
            GroupFit::RelatedAggregate
        } else {
            GroupFit::Unaggregated
        }
    }

    fn error(self) -> Option<Error> {
        match self {
            GroupFit::Aggregated => None,
            GroupFit::RelatedAggregate => Some(msg::related_aggregate_in_grouped_query()),
            GroupFit::Unaggregated => Some(msg::ungrouped_unaggregated_column()),
        }
    }
}

/// The standalone `\\` sorting expressions of a stage, compiled.
pub struct ConvertedSortExprs {
    pub sorting: Vec<SortEntry>,
    /// For each entry that would be invalid in a grouped query unless it turns out to match a
    /// grouping column: how it fails to fit, and where it was written. See
    /// [`ConvertedSortExprs::validate_grouped`].
    misfits: Vec<(usize, GroupFit, Loc)>,
}

impl ConvertedSortExprs {
    /// Checks the sorting expressions against the stage's `grouping`, which is empty unless the
    /// stage is grouped. SQL can only sort groups by something that has a value for each group:
    /// a grouping expression, or an aggregate.
    pub fn validate_grouped(&self, grouping: &[SqlExpr]) -> Result<(), Error> {
        if grouping.is_empty() {
            return Ok(());
        }
        for (index, fit, loc) in &self.misfits {
            let sort = &self.sorting[*index].expr;
            if !grouping.iter().any(|g| g.content == sort.content) {
                let err = match fit {
                    GroupFit::RelatedAggregate => msg::related_aggregate_in_grouped_query(),
                    _ => msg::ungrouped_unaggregated_sort(),
                };
                return Err(err.at(*loc));
            }
        }
        Ok(())
    }
}

/// Converts standalone `\\` sorting expressions into SQL sort entries, preserving the order in
/// which they were listed (no ordinal handling — listed order is the precedence). Each expression
/// is compiled directly; unlike column sorts, there is no result-column alias to resolve, since
/// these are defined before the result columns.
pub fn convert_sort_exprs(
    sorting: Vec<SortExpr>,
    scope: &mut Scope,
) -> Result<ConvertedSortExprs, Error> {
    let mut entries = Vec::with_capacity(sorting.len());
    let mut misfits = Vec::new();
    for (index, sort_expr) in sorting.into_iter().enumerate() {
        let fit = GroupFit::of(&sort_expr.expr);
        if fit != GroupFit::Aggregated {
            misfits.push((index, fit, sort_expr.expr.loc));
        }
        entries.push(SortEntry {
            expr: convert_expr(sort_expr.expr, scope)?,
            direction: sort_expr.direction,
            nulls_sort: sort_expr.nulls_sort,
        });
    }
    Ok(ConvertedSortExprs {
        sorting: entries,
        misfits,
    })
}

pub fn convert_result_columns(
    result_columns: Vec<ResultColumnStatement>,
    scope: &mut Scope,
) -> Result<ConvertedResultColumns, Error> {
    let mut output = Output::default();
    for column_statement in result_columns {
        match column_statement {
            ResultColumnStatement::Spec(spec) => handle_spec(spec, &mut output, scope)?,
            ResultColumnStatement::Glob(glob) => handle_glob(glob, &mut output, scope)?,
        }
    }
    let grouping: Vec<SqlExpr> = output.grouping_stack.into();
    if let Some((fit, loc)) = output.misfit.filter(|_| !grouping.is_empty()) {
        if let Some(err) = fit.error() {
            return Err(err.at(loc));
        }
    }
    Ok(ConvertedResultColumns {
        columns: output.columns,
        sorting: output.sorting_stack.into(),
        grouping,
        column_annotations: output.column_annotations,
        output_names: output.output_names,
        named: output.named,
        output_types: output.output_types,
    })
}

fn handle_spec(spec: ColumnSpec, output: &mut Output, scope: &mut Scope) -> Result<(), Error> {
    let ColumnControl {
        sort,
        group,
        is_partition_by: _,
        is_hidden: _,
    } = spec.column_control;
    let is_grouped = group.is_some();
    let fit = GroupFit::of(&spec.expr);
    let (output_name, is_named) =
        output_name_for_spec(&spec.alias, &spec.expr, output.columns.len());
    let loc = spec.expr.loc;
    let output_type = infer_type(&spec.expr, scope);
    let expr = convert_expr(spec.expr, scope)?;
    let alias = spec.alias;
    if let Some(sort_spec) = sort {
        let sorting_expr = alias
            .as_ref()
            .map(|a| SqlExpr::atom(scope.options.dialect.quote_identifier(a)))
            .unwrap_or_else(|| expr.clone());
        output.sorting_stack.push(sorting_expr, sort_spec);
    }
    if let Some(group_spec) = group {
        output.grouping_stack.push(expr.clone(), group_spec);
    }
    if !is_grouped && fit != GroupFit::Aggregated {
        output.misfit.get_or_insert((fit, loc));
    }
    output.columns.push(Column { expr, alias });
    output.column_annotations.push(spec.annotation);
    output.output_names.push(output_name);
    output.named.push(is_named);
    output.output_types.push(output_type);
    Ok(())
}

fn handle_glob(glob: ColumnGlob, output: &mut Output, scope: &mut Scope) -> Result<(), Error> {
    scope.with_path_prefix(glob.head.clone(), |scope| -> Result<(), Error> {
        for spec in glob.specs.iter() {
            if let Some(ref sort_spec) = spec.column_control.sort {
                let sql_expr = convert_expr(spec.expr.clone(), scope)?;
                output.sorting_stack.push(sql_expr, sort_spec.to_owned());
            }
            if let Some(ref group_spec) = spec.column_control.group {
                let sql_expr = convert_expr(spec.expr.clone(), scope)?;
                output.grouping_stack.push(sql_expr, group_spec.to_owned());
            }
        }
        Ok(())
    })?;

    let (table, table_alias) = if glob.head.is_empty() {
        (scope.get_base_table(), scope.get_base_alias().to_owned())
    } else {
        let clarified_path = clarify_path(glob.head, scope)?;
        if let Some(tail) = clarified_path.tail {
            let err = match tail {
                ClarifiedPathTail::Column(col) => msg::column_glob_after_non_fk_column(&col),
                ClarifiedPathTail::ChainToMany(_) => msg::column_glob_on_path_to_many(),
            };
            return Err(err.at(glob.loc));
        }
        let Some(chain_to_one) = clarified_path.head else {
            return Err(msg::empty_path().at(glob.loc));
        };
        let table = scope
            .schema
            .tables
            .get(&chain_to_one.get_ending_table_id())
            .unwrap();
        let table_alias = scope.join_chain_to_one(&chain_to_one);
        (table, table_alias)
    };

    let mut hidden_columns: HashSet<usize> = HashSet::new();
    let mut grouped_columns: HashSet<usize> = HashSet::new();
    let mut column_aliases: HashMap<usize, String> = HashMap::new();
    let mut column_annotations_map: HashMap<usize, AnnotationValue> = HashMap::new();

    for spec in glob.specs {
        if let ExprKind::Path(ref path) = spec.expr.kind {
            if let Ok(PathPartKind::Column(column_name)) =
                path.iter().map(|p| &p.kind).exactly_one()
            {
                let column_id = scope
                    .options
                    .resolve_identifier(&table.column_lookup, column_name)
                    .copied()
                    .ok_or_else(|| {
                        msg::col_not_in_table(column_name, &table.written_name()).at(spec.expr.loc)
                    })?;
                if spec.column_control.is_hidden {
                    hidden_columns.insert(column_id);
                }
                if spec.column_control.group.is_some() {
                    grouped_columns.insert(column_id);
                }
                if let Some(alias) = spec.alias {
                    column_aliases.insert(column_id, alias);
                }
                if let Some(annotation) = spec.annotation {
                    column_annotations_map.insert(column_id, annotation);
                }
            }
        }
    }

    for column in table.columns.values().sorted_by_key(|c| c.id) {
        let expr = scope.table_column_expr(&table_alias, &column.name);
        let alias = column_aliases.get(&column.id).cloned();
        if !hidden_columns.contains(&column.id) {
            // A glob emits raw table columns, which are not aggregates. In a grouped query each
            // such column must therefore be one of the grouping columns.
            if !grouped_columns.contains(&column.id) {
                output
                    .misfit
                    .get_or_insert((GroupFit::Unaggregated, glob.loc));
            }
            // The output name is the column's alias if one was given, otherwise the column name.
            let output_name = alias.clone().unwrap_or_else(|| column.name.clone());
            output.columns.push(Column { expr, alias });
            output
                .column_annotations
                .push(column_annotations_map.get(&column.id).cloned());
            output.output_names.push(output_name);
            output.named.push(true);
            output.output_types.push(column.r#type.clone());
        }
    }
    Ok(())
}

mod sorting {
    use querydown_parser::ast::SortSpec;

    use crate::sql::tree::{SortEntry, SqlExpr};

    pub struct UnplacedSortEntry {
        entry: SortEntry,
        ordinal: Option<u32>,
    }

    pub struct SortingStack {
        entries: Vec<UnplacedSortEntry>,
    }

    impl Default for SortingStack {
        fn default() -> Self {
            Self::new()
        }
    }

    impl SortingStack {
        pub fn new() -> Self {
            Self {
                entries: Vec::new(),
            }
        }

        pub fn push(&mut self, expr: SqlExpr, sort_spec: SortSpec) {
            let entry = UnplacedSortEntry {
                entry: SortEntry {
                    expr,
                    direction: sort_spec.direction,
                    nulls_sort: sort_spec.nulls_sort,
                },
                ordinal: sort_spec.ordinal,
            };
            self.entries.push(entry);
        }
    }

    impl From<SortingStack> for Vec<SortEntry> {
        fn from(stack: SortingStack) -> Self {
            let mut entries = stack.entries;
            let max_ordinal = entries.iter().filter_map(|e| e.ordinal).max().unwrap_or(0);
            entries.sort_by_key(|entry| entry.ordinal.unwrap_or(max_ordinal.saturating_add(1)));
            entries.into_iter().map(|entry| entry.entry).collect()
        }
    }
}

mod grouping {
    use querydown_parser::ast::GroupSpec;

    use crate::sql::tree::SqlExpr;

    struct UnplacedGroupEntry {
        expr: SqlExpr,
        ordinal: Option<u32>,
    }

    /// Collects the `GROUP BY` expressions, ordering them by their ordinals (`\g1`, `\g2`, …).
    /// Entries without an explicit ordinal keep the order in which they appear, after all entries
    /// that do specify an ordinal — mirroring [`super::sorting::SortingStack`].
    pub struct GroupingStack {
        entries: Vec<UnplacedGroupEntry>,
    }

    impl Default for GroupingStack {
        fn default() -> Self {
            Self::new()
        }
    }

    impl GroupingStack {
        pub fn new() -> Self {
            Self {
                entries: Vec::new(),
            }
        }

        pub fn push(&mut self, expr: SqlExpr, group_spec: GroupSpec) {
            self.entries.push(UnplacedGroupEntry {
                expr,
                ordinal: group_spec.ordinal,
            });
        }
    }

    impl From<GroupingStack> for Vec<SqlExpr> {
        fn from(stack: GroupingStack) -> Self {
            let mut entries = stack.entries;
            let max_ordinal = entries.iter().filter_map(|e| e.ordinal).max().unwrap_or(0);
            entries.sort_by_key(|entry| entry.ordinal.unwrap_or(max_ordinal.saturating_add(1)));
            entries.into_iter().map(|entry| entry.expr).collect()
        }
    }
}
